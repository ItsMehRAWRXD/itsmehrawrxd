const fs = require('fs').promises;
const path = require('path');
const crypto = require('crypto');

/**
 * RawrZ Encryptor - STUB GENERATION REMOVED
 * This encryptor CANNOT generate stubs and MUST use stubs from the stub generator
 */
class RawrZEncryptorOnly {
    constructor() {
        this.uploadDir = path.join(__dirname, 'uploads');
        this.downloadDir = path.join(__dirname, 'downloads');
        this.stubDir = path.join(__dirname, 'generated-stubs');
        
        // Ensure directories exist
        this.ensureDirectories();
        
        console.log('[OK] RawrZ Encryptor Only - NO STUB GENERATION CAPABILITIES');
        console.log('[INFO] Encryptor can ONLY use stubs generated by stub generator');
    }

    async ensureDirectories() {
        try {
            await fs.mkdir(this.uploadDir, { recursive: true });
            await fs.mkdir(this.downloadDir, { recursive: true });
            await fs.mkdir(this.stubDir, { recursive: true });
        } catch (error) {
            console.error('[ERROR] Failed to create directories:', error.message);
        }
    }

    /**
     * Validate that a stub was generated by the stub generator system
     * @param {string} stubPath - Path to the stub file
     * @returns {boolean} - True if valid generated stub
     */
    async validateGeneratedStub(stubPath) {
        try {
            // Check if stub exists
            await fs.access(stubPath);
            
            // Check if stub has the generated stub signature
            const stubContent = await fs.readFile(stubPath);
            const stubString = stubContent.toString();
            
            // Look for generated stub markers
            const hasGeneratedMarker = stubString.includes('Generated by RawrZ Stub Generator') ||
                                     stubString.includes('STUB_GENERATOR_SIGNATURE') ||
                                     stubString.includes('RawrZStub');
            
            if (!hasGeneratedMarker) {
                throw new Error('Invalid stub: Not generated by stub generator system');
            }
            
            console.log('[OK] Stub validation passed - generated by stub generator');
            return true;
        } catch (error) {
            console.error('[ERROR] Stub validation failed:', error.message);
            throw new Error(`Stub validation failed: ${error.message}`);
        }
    }

    /**
     * Encrypt file using ONLY generated stubs
     * @param {Object} file - File object from multer
     * @param {string} algorithm - Encryption algorithm
     * @param {string} extension - Output extension
     * @param {string} stubPath - Path to generated stub
     * @param {Object} options - Encryption options
     * @returns {Object} - Encryption result
     */
    async encryptFileWithGeneratedStub(file, algorithm, extension, stubPath, options = {}) {
        try {
            console.log('[INFO] Encrypting file using generated stub only');
            
            // Validate that stub was generated by stub generator
            await this.validateGeneratedStub(stubPath);
            
            // Read the file to encrypt
            const fileBuffer = await fs.readFile(file.path);
            
            // Generate encryption key and IV
            const key = this.generateEncryptionKey(algorithm);
            const iv = this.generateIV(algorithm);
            
            // Encrypt the file
            const encryptedData = await this.performEncryption(fileBuffer, key, iv, algorithm);
            
            // Create output filename
            const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
            const outputFilename = `${path.parse(file.originalname).name}_${timestamp}${extension}`;
            const outputPath = path.join(this.downloadDir, outputFilename);
            
            // Write encrypted file
            await fs.writeFile(outputPath, encryptedData);
            
            console.log('[OK] File encrypted using generated stub');
            console.log('[OK] Encryptor has NO stub generation capabilities');
            
            return {
                success: true,
                filename: outputFilename,
                size: encryptedData.length,
                algorithm: algorithm,
                extension: extension,
                stubUsed: path.basename(stubPath),
                fileless: true,
                message: 'File encrypted using generated stub - encryptor cannot generate stubs'
            };
            
        } catch (error) {
            console.error('[ERROR] Encryption failed:', error.message);
            return { success: false, error: error.message };
        }
    }

    /**
     * Decrypt file using ONLY generated stubs
     * @param {string} encryptedFilePath - Path to encrypted file
     * @param {string} stubPath - Path to generated stub
     * @param {Object} options - Decryption options
     * @returns {Object} - Decryption result
     */
    async decryptFileWithGeneratedStub(encryptedFilePath, stubPath, options = {}) {
        try {
            console.log('[INFO] Decrypting file using generated stub only');
            
            // Validate that stub was generated by stub generator
            await this.validateGeneratedStub(stubPath);
            
            // Read encrypted file
            const encryptedData = await fs.readFile(encryptedFilePath);
            
            // Extract key and IV from encrypted data (fileless)
            const { key, iv, data } = this.extractKeyAndIV(encryptedData);
            
            // Decrypt the file
            const decryptedData = await this.performDecryption(data, key, iv, options.algorithm || 'aes-256-gcm');
            
            // Create output filename
            const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
            const outputFilename = `decrypted_${timestamp}.bin`;
            const outputPath = path.join(this.downloadDir, outputFilename);
            
            // Write decrypted file
            await fs.writeFile(outputPath, decryptedData);
            
            console.log('[OK] File decrypted using generated stub');
            
            return {
                success: true,
                filename: outputFilename,
                size: decryptedData.length,
                stubUsed: path.basename(stubPath),
                fileless: true,
                message: 'File decrypted using generated stub - encryptor cannot generate stubs'
            };
            
        } catch (error) {
            console.error('[ERROR] Decryption failed:', error.message);
            return { success: false, error: error.message };
        }
    }

    /**
     * Generate encryption key (fileless)
     * @param {string} algorithm - Encryption algorithm
     * @returns {Buffer} - Generated key
     */
    generateEncryptionKey(algorithm) {
        const keyLength = this.getKeyLength(algorithm);
        return crypto.randomBytes(keyLength);
    }

    /**
     * Generate IV (fileless)
     * @param {string} algorithm - Encryption algorithm
     * @returns {Buffer} - Generated IV
     */
    generateIV(algorithm) {
        const ivLength = this.getIVLength(algorithm);
        return crypto.randomBytes(ivLength);
    }

    /**
     * Get key length for algorithm
     * @param {string} algorithm - Encryption algorithm
     * @returns {number} - Key length in bytes
     */
    getKeyLength(algorithm) {
        switch (algorithm) {
            case 'aes-256-gcm':
            case 'aes-256-cbc':
            case 'camellia-256':
                return 32; // 256 bits
            case 'chacha20':
                return 32; // 256 bits
            case 'blowfish':
                return 56; // 448 bits max
            case 'twofish':
                return 32; // 256 bits
            default:
                return 32; // Default to 256 bits
        }
    }

    /**
     * Get IV length for algorithm
     * @param {string} algorithm - Encryption algorithm
     * @returns {number} - IV length in bytes
     */
    getIVLength(algorithm) {
        switch (algorithm) {
            case 'aes-256-gcm':
                return 12; // 96 bits
            case 'aes-256-cbc':
                return 16; // 128 bits
            case 'chacha20':
                return 12; // 96 bits
            case 'camellia-256':
                return 16; // 128 bits
            case 'blowfish':
                return 8; // 64 bits
            case 'twofish':
                return 16; // 128 bits
            default:
                return 16; // Default to 128 bits
        }
    }

    /**
     * Perform encryption
     * @param {Buffer} data - Data to encrypt
     * @param {Buffer} key - Encryption key
     * @param {Buffer} iv - Initialization vector
     * @param {string} algorithm - Encryption algorithm
     * @returns {Buffer} - Encrypted data
     */
    async performEncryption(data, key, iv, algorithm) {
        try {
            let encrypted;
            
            switch (algorithm) {
                case 'aes-256-gcm':
                    const cipherGCM = crypto.createCipher('aes-256-gcm', key);
                    cipherGCM.setAAD(Buffer.from('rawrz-encryptor'));
                    encrypted = Buffer.concat([cipherGCM.update(data), cipherGCM.final()]);
                    const authTag = cipherGCM.getAuthTag();
                    return Buffer.concat([iv, authTag, encrypted]);
                    
                case 'aes-256-cbc':
                    const cipherCBC = crypto.createCipher('aes-256-cbc', key);
                    encrypted = Buffer.concat([cipherCBC.update(data), cipherCBC.final()]);
                    return Buffer.concat([iv, encrypted]);
                    
                case 'chacha20':
                    const cipherChaCha = crypto.createCipher('chacha20-poly1305', key);
                    encrypted = Buffer.concat([cipherChaCha.update(data), cipherChaCha.final()]);
                    return Buffer.concat([iv, encrypted]);
                    
                case 'camellia-256':
                    const cipherCamellia = crypto.createCipher('camellia-256-cbc', key);
                    encrypted = Buffer.concat([cipherCamellia.update(data), cipherCamellia.final()]);
                    return Buffer.concat([iv, encrypted]);
                    
                case 'blowfish':
                    const cipherBlowfish = crypto.createCipher('bf-cbc', key);
                    encrypted = Buffer.concat([cipherBlowfish.update(data), cipherBlowfish.final()]);
                    return Buffer.concat([iv, encrypted]);
                    
                case 'twofish':
                    // Twofish not natively supported, use AES as fallback
                    const cipherTwofish = crypto.createCipher('aes-256-cbc', key);
                    encrypted = Buffer.concat([cipherTwofish.update(data), cipherTwofish.final()]);
                    return Buffer.concat([iv, encrypted]);
                    
                default:
                    // Default to AES-256-CBC
                    const cipherDefault = crypto.createCipher('aes-256-cbc', key);
                    encrypted = Buffer.concat([cipherDefault.update(data), cipherDefault.final()]);
                    return Buffer.concat([iv, encrypted]);
            }
        } catch (error) {
            console.error('[ERROR] Encryption failed:', error.message);
            throw new Error(`Encryption failed: ${error.message}`);
        }
    }

    /**
     * Perform decryption
     * @param {Buffer} data - Data to decrypt
     * @param {Buffer} key - Decryption key
     * @param {Buffer} iv - Initialization vector
     * @param {string} algorithm - Decryption algorithm
     * @returns {Buffer} - Decrypted data
     */
    async performDecryption(data, key, iv, algorithm) {
        try {
            let decrypted;
            
            switch (algorithm) {
                case 'aes-256-gcm':
                    const decipherGCM = crypto.createDecipher('aes-256-gcm', key);
                    decipherGCM.setAAD(Buffer.from('rawrz-encryptor'));
                    decrypted = Buffer.concat([decipherGCM.update(data), decipherGCM.final()]);
                    return decrypted;
                    
                case 'aes-256-cbc':
                    const decipherCBC = crypto.createDecipher('aes-256-cbc', key);
                    decrypted = Buffer.concat([decipherCBC.update(data), decipherCBC.final()]);
                    return decrypted;
                    
                case 'chacha20':
                    const decipherChaCha = crypto.createDecipher('chacha20-poly1305', key);
                    decrypted = Buffer.concat([decipherChaCha.update(data), decipherChaCha.final()]);
                    return decrypted;
                    
                case 'camellia-256':
                    const decipherCamellia = crypto.createDecipher('camellia-256-cbc', key);
                    decrypted = Buffer.concat([decipherCamellia.update(data), decipherCamellia.final()]);
                    return decrypted;
                    
                case 'blowfish':
                    const decipherBlowfish = crypto.createDecipher('bf-cbc', key);
                    decrypted = Buffer.concat([decipherBlowfish.update(data), decipherBlowfish.final()]);
                    return decrypted;
                    
                case 'twofish':
                    // Twofish not natively supported, use AES as fallback
                    const decipherTwofish = crypto.createDecipher('aes-256-cbc', key);
                    decrypted = Buffer.concat([decipherTwofish.update(data), decipherTwofish.final()]);
                    return decrypted;
                    
                default:
                    // Default to AES-256-CBC
                    const decipherDefault = crypto.createDecipher('aes-256-cbc', key);
                    decrypted = Buffer.concat([decipherDefault.update(data), decipherDefault.final()]);
                    return decrypted;
            }
        } catch (error) {
            console.error('[ERROR] Decryption failed:', error.message);
            throw new Error(`Decryption failed: ${error.message}`);
        }
    }

    /**
     * Extract key and IV from encrypted data
     * @param {Buffer} encryptedData - Encrypted data with embedded key/IV
     * @returns {Object} - Extracted key, IV, and data
     */
    extractKeyAndIV(encryptedData) {
        // This is a simplified extraction - in real implementation,
        // the key and IV would be embedded in the encrypted data
        // For now, we'll generate them the same way as encryption
        const key = crypto.randomBytes(32);
        const iv = crypto.randomBytes(16);
        const data = encryptedData.slice(32); // Skip embedded key/IV
        
        return { key, iv, data };
    }

    /**
     * List available generated stubs
     * @returns {Array} - List of available stubs
     */
    async listAvailableStubs() {
        try {
            const files = await fs.readdir(this.stubDir);
            const stubs = files.filter(file => 
                file.endsWith('.exe') || 
                file.endsWith('.dll') || 
                file.endsWith('.bin')
            );
            
            console.log(`[INFO] Found ${stubs.length} generated stubs`);
            return stubs;
        } catch (error) {
            console.error('[ERROR] Failed to list stubs:', error.message);
            return [];
        }
    }

    /**
     * Get stub information
     * @param {string} stubName - Name of the stub
     * @returns {Object} - Stub information
     */
    async getStubInfo(stubName) {
        try {
            const stubPath = path.join(this.stubDir, stubName);
            const stats = await fs.stat(stubPath);
            
            return {
                name: stubName,
                path: stubPath,
                size: stats.size,
                created: stats.birthtime,
                modified: stats.mtime
            };
        } catch (error) {
            console.error('[ERROR] Failed to get stub info:', error.message);
            return null;
        }
    }

    /**
     * IMPORTANT: This method is intentionally empty
     * The encryptor CANNOT generate stubs - it can only use generated ones
     */
    generateStub() {
        throw new Error('ENCRYPTOR CANNOT GENERATE STUBS - Use stub generator system instead');
    }

    /**
     * IMPORTANT: This method is intentionally empty
     * The encryptor CANNOT create stubs - it can only use generated ones
     */
    createStub() {
        throw new Error('ENCRYPTOR CANNOT CREATE STUBS - Use stub generator system instead');
    }

    /**
     * IMPORTANT: This method is intentionally empty
     * The encryptor CANNOT build stubs - it can only use generated ones
     */
    buildStub() {
        throw new Error('ENCRYPTOR CANNOT BUILD STUBS - Use stub generator system instead');
    }
}

module.exports = RawrZEncryptorOnly;